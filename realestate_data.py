import json
import pandas as pd

# -------------------------------
# 1️⃣ Load JSON File
# -------------------------------
with open('/content/drive/MyDrive/Guvi/Dataset/agents_20k.json', 'r') as f:
    data = json.load(f)

# If JSON is a list → convert directly
# If single record → wrap in list
if isinstance(data, dict):
    data = [data]

# -------------------------------
# 2️⃣ Convert to DataFrame
# -------------------------------
df = pd.json_normalize(data)

print("Original Data:")
print(df.head())


# -------------------------------
# 3️⃣ Standardize Column Names
# -------------------------------
df.columns = df.columns.str.lower().str.strip()

# Rename for consistency
df.rename(columns={
    'agent_id': 'agent_id',
    'name': 'agent_name',
    'phone': 'phone',
    'email': 'email'
}, inplace=True)


# -------------------------------
# 4️⃣ Clean Phone Numbers
# -------------------------------
df['phone'] = df['phone'].astype(str)

# Remove spaces
df['phone'] = df['phone'].str.replace(' ', '')

# Keep only numbers + +
df['phone'] = df['phone'].str.replace(r'[^\d+]', '', regex=True)


# -------------------------------
# 5️⃣ Clean Email
# -------------------------------
df['email'] = df['email'].str.lower().str.strip()


# -------------------------------
# 6️⃣ Handle Missing Values
# -------------------------------
df.fillna({
    'agent_name': 'Unknown',
    'phone': 'Not Available',
    'email': 'Not Available'
}, inplace=True)


# -------------------------------
# 7️⃣ Remove Duplicates
# -------------------------------
df.drop_duplicates(subset=['agent_id'], inplace=True)


# -------------------------------
# 8️⃣ Final Output
# -------------------------------
print("\nCleaned Data:")
print(df)

print("\nData Info:")
print(df.info())


# -------------------------------
# 9️⃣ Save Clean Data
# -------------------------------
df.to_csv("cleaned_agents.csv", index=False)

print("\n✅ Agents Data Prepared Successfully!")

