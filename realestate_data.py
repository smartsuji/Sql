# -------------------------------
# 9️⃣ Final Output
# -------------------------------
print("\nCleaned Data:")
print(df.head())

print("\nData Info:")
print(df.info())


# -------------------------------
# 🔟 Save Clean Data
# -------------------------------
df.to_csv("cleaned_listings.csv", index=False)

print("\n✅ Listings Data Prepared Successfully!")

