df.rename(columns={
    'listing_id': 'listing_id',
    'city': 'location',
    'property_type': 'property_type',
    'price': 'price',
    'sqft': 'area',
    'date_listed': 'date_listed',
    'agent_id': 'agent_id',
    'latitude': 'latitude',
    'longitude': 'longitude'
}, inplace=True)


# -------------------------------
# 4️⃣ Convert Date Format
# -------------------------------
if 'date_listed' in df.columns:
    df['date_listed'] = pd.to_datetime(df['date_listed'], errors='coerce')
    df['date_listed'] = df['date_listed'].dt.strftime('%Y-%m-%d')


# -------------------------------
# 5️⃣ Convert Numeric Fields
# -------------------------------
numeric_cols = ['price', 'area', 'latitude', 'longitude']

for col in numeric_cols:
    if col in df.columns:
        df[col] = pd.to_numeric(df[col], errors='coerce')


# -------------------------------
# 6️⃣ Clean Text Fields
# -------------------------------
if 'location' in df.columns:
    df['location'] = df['location'].str.strip().str.title()

if 'property_type' in df.columns:
    df['property_type'] = df['property_type'].str.strip().str.title()


# -------------------------------
# 7️⃣ Handle Missing Values
# -------------------------------
df.fillna({
    'price': 0,
    'area': 0,
    'location': 'Unknown',
    'property_type': 'Unknown'
}, inplace=True)


# -------------------------------
# 8️⃣ Remove Duplicates
# -------------------------------
